/**
 * Reads PNG metadata with sharp (never opens/renders an image for a human).
 * Reports alpha channel presence for ship-vs-source decisions.
 * Usage: node scripts/alpha-check.mjs
 */
import sharp from "sharp";
import { readdirSync } from "node:fs";
import { join } from "node:path";

const dir = "public/assets/me";
const files = readdirSync(dir).filter((f) => f.endsWith(".png"));

const rows = await Promise.all(
  files.map(async (f) => {
    const meta = await sharp(join(dir, f)).metadata();
    return { file: f, w: meta.width, h: meta.height, alpha: meta.hasAlpha === true };
  })
);

const lines = rows.map((r) => `| ${r.file} | ${r.w}x${r.h} | ${r.alpha ? "YES" : "no"} |`);
const md = `# ALPHA report (generated by scripts/alpha-check.mjs — no images viewed)\n\n| file | size | hasAlpha |\n|---|---|---|\n${lines.join("\n")}\n`;
console.log(md);

// brain/ is not in version control, so create it rather than throwing ENOENT.
const fs = await import("node:fs/promises");
await fs.mkdir("brain", { recursive: true });
await fs.writeFile("brain/ALPHA.md", md, "utf8");
